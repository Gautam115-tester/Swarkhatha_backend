-- SwarKatha migration: centralized artwork (ONE ALBUM = ONE IMAGE, ONE SERIES = ONE IMAGE).
-- Run this in the Supabase SQL editor AFTER migration_image_storage_drime.sql.
-- Safe to run more than once. Contains NO destructive statements: it only adds
-- columns/indexes. Existing data is consolidated by scripts/consolidate-artwork.js
-- (dry-run by default), after which you re-run THIS file once so the unique
-- indexes below can be created.
--
-- WHY
-- An album used to be identified by (name, artist). Two problems followed:
--   1. "Love Aaj Kal" (2009) and "Love Aaj Kal" (2020) were indistinguishable by
--      the backend, and the listener app grouped albums by title alone.
--   2. A soundtrack credited to many artists was split into one album row (and one
--      uploaded cover) per artist string.
-- An album is now identified by (normalized name, release year). The album row is
-- the single owner of the album's artwork (cover_image_url + image_storage_*);
-- tracks only point at it through album_id. Series are identified by their
-- normalized title and own their artwork the same way.

-- ============ ALBUMS ============
alter table albums add column if not exists release_year int;

-- Normalized, case/whitespace-insensitive name used for identity. Generated by the
-- database so it can never drift from `name`. Must stay in sync with
-- normalizeKey() in lib/artwork.js.
alter table albums add column if not exists name_key text
  generated always as (lower(regexp_replace(btrim(name), '\s+', ' ', 'g'))) stored;

-- (name, artist) is no longer the identity of an album.
alter table albums drop constraint if exists albums_name_artist_key;

create index if not exists idx_albums_name_key on albums (name_key);

-- ============ STORY SERIES ============
alter table story_series add column if not exists title_key text
  generated always as (lower(regexp_replace(btrim(title), '\s+', ' ', 'g'))) stored;

create index if not exists idx_story_series_title_key on story_series (title_key);

-- ============ UNIQUE IDENTITY (only once existing duplicates are gone) ============
-- A unique index cannot be created while duplicates exist, and merging duplicates
-- needs human review (same name + unknown year could be two different releases).
-- So: if duplicates exist this prints a NOTICE and skips; run
-- `node scripts/consolidate-artwork.js` (dry-run first), then re-run this file.
do $$
begin
  if exists (
    select 1 from albums group by name_key, coalesce(release_year, 0) having count(*) > 1
  ) then
    raise notice 'albums: duplicate (name, release_year) rows exist - run scripts/consolidate-artwork.js, then re-run this migration to add the unique index.';
  else
    create unique index if not exists albums_name_year_uniq
      on albums (name_key, (coalesce(release_year, 0)));
  end if;

  if exists (
    select 1 from story_series group by title_key having count(*) > 1
  ) then
    raise notice 'story_series: duplicate titles exist - run scripts/consolidate-artwork.js, then re-run this migration to add the unique index.';
  else
    create unique index if not exists story_series_title_key_uniq
      on story_series (title_key);
  end if;
end $$;

-- Lookups used when deciding whether a Drime image file is still referenced.
create index if not exists idx_albums_image_file on albums (image_storage_file_id);
create index if not exists idx_story_series_image_file on story_series (image_storage_file_id);

