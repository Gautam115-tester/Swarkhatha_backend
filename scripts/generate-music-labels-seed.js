'use strict';
/**
 * Generates supabase/seed_music_labels.sql from lib/classification/taxonomy.js
 * (the single source of truth). `node scripts/generate-music-labels-seed.js`
 * rewrites the file; `--check` exits 1 if the committed file is out of date
 * (test/classification/taxonomy.test.js runs that check).
 */
const fs = require('node:fs');
const path = require('node:path');
const { ALL_LABELS } = require('../lib/classification/taxonomy');

const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);

function render() {
  const rows = ALL_LABELS.map((l) => {
    const parent = l.parent ? `(select id from music_labels where dimension = ${q(l.dimension)} and slug = ${q(l.parent)})` : 'null';
    return `  (${q(l.dimension)}, ${q(l.slug)}, ${q(l.name)}, ${parent}, ${q(l.description || null)}, ${q(l.legacy || null)})`;
  });
  // One statement per row so a child's parent subselect always sees the parent inserted just before it.
  const stmts = ALL_LABELS.map((l, i) =>
    `insert into music_labels (dimension, slug, name, parent_id, description, legacy_name) values\n${rows[i]}\n` +
    `on conflict (dimension, slug) do update set name = excluded.name, parent_id = excluded.parent_id,\n` +
    `  description = excluded.description, legacy_name = excluded.legacy_name, updated_at = now();`);
  return [
    '-- GENERATED by scripts/generate-music-labels-seed.js from lib/classification/taxonomy.js -- do not edit by hand.',
    '-- Idempotent controlled-vocabulary seed for music_labels. Run after migration_music_classification.sql.',
    '-- Re-running updates names/hierarchy and never deletes a label that is already assigned to tracks.',
    ...stmts, ''
  ].join('\n');
}

const target = path.join(__dirname, '..', 'supabase', 'seed_music_labels.sql');
if (require.main === module) {
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
    if (current !== render()) { console.error('seed_music_labels.sql is out of date: run node scripts/generate-music-labels-seed.js'); process.exit(1); }
    console.log('seed_music_labels.sql is up to date');
  } else {
    fs.writeFileSync(target, render());
    console.log(`wrote ${target} (${ALL_LABELS.length} labels)`);
  }
}
module.exports = { render, target };
